"""Generates lib/xml_strings/*/strings.xml from strings_src.py.

values/ (EN) and values-vi/ are the real translations. dsp_base's CommLocalize
also loads the folder of the device language for its 14 other locales, so those
folders get the English text: Muvik shows English for untranslated languages
(P00-09) and the loader never hits a missing asset.

Usage: python tool/gen_strings.py
"""
import os
import sys
from xml.sax.saxutils import escape

sys.path.insert(0, os.path.dirname(__file__))
from strings_src import S  # noqa: E402

ROOT = os.path.join(os.path.dirname(__file__), '..', 'lib', 'xml_strings')


def esc(v):
    return escape(v).replace("'", "\\'").replace('"', '\\"')


# Locale folders known to dsp_base CommLocalize without a Muvik translation.
EN_FALLBACK = ('ar', 'de', 'es', 'fa', 'fr', 'id', 'it', 'ja', 'ko', 'pt', 'ru',
               'tr', 'zh-rCN', 'zh-rTW')

TARGETS = [('values', 0), ('values-vi', 1)] + [(f'values-{c}', 0) for c in EN_FALLBACK]

for folder, idx in TARGETS:
    os.makedirs(os.path.join(ROOT, folder), exist_ok=True)
    note = ' English fallback: no translation yet.' if folder[7:] in EN_FALLBACK else ''
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             f'<!-- Generated by tool/gen_strings.py. Edit tool/strings_src.py instead.{note} -->',
             '<resources>']
    for k in sorted(S):
        lines.append(f'    <string name="{k}">{esc(S[k][idx])}</string>')
    lines.append('</resources>')
    with open(os.path.join(ROOT, folder, 'strings.xml'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
print(f'{len(S)} keys written to {len(TARGETS)} locale folders')
